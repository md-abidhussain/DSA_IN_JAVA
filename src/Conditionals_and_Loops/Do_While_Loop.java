package Conditionals_and_Loops;

public class Do_While_Loop {
    public static void main(String[] args) {
        // do - while loop
        /* syntax

        do {
        body;
        } while (condition);
         */

    int n = 1;
    do {
        System.out.println(n);
        n++;
    } while (n <= 5);


    }
}

// do - while loop will execute atleast once irrespective of condition
