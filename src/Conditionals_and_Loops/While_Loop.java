package Conditionals_and_Loops;

public class While_Loop {
    public static void main(String [] args) {
        // While Loops
        /* Syntax
        while (condition) {
            body;
           increment/decrement;
           }
         */
        int num = 1;
        while (num <=5) {
            System.out.println(num);
            num += 1;
        }
    }
}

// use while loop when you don't know how many times the loop will run


